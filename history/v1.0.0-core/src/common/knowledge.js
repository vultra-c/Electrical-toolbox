export function formulasOf(group) {
  var out = []
  for (var i = 0; i < FORMULAS.length; i++) {
    if (FORMULAS[i].g === group) out.push(FORMULAS[i])
  }
  return out
}

export function groupName(key) {
  for (var i = 0; i < GROUPS.length; i++) {
    if (GROUPS[i].key === key) return GROUPS[i].name
  }
  return ''
}

export function groupColor(key) {
  for (var i = 0; i < GROUPS.length; i++) {
    if (GROUPS[i].key === key) return GROUPS[i].color
  }
  return '#4FC3F7'
}
